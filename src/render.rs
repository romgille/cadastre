//! Renders the documentation pages.
//!
//! Rendering is a pure function of the sanitized containers: the same input
//! always produces byte-identical output. In particular no page contains a
//! timestamp, otherwise every run would rewrite every file and sync tools
//! would transfer everything again. The moment something changed is recorded
//! in the changelog instead.
//!
//! Every value that comes from Docker is written inside an inline code span,
//! so a hostile container name or label cannot inject Markdown or HTML.

use std::collections::{BTreeMap, BTreeSet};

use crate::model::{Container, Mount, Port, STANDALONE};

/// Second line of every generated page. It marks the file as ours so that
/// stale pages can be pruned without ever touching something a person wrote.
pub const MARKER: &str = "<!-- cadastre:generated -->";

const NOTICE: &str =
    "<!-- Generated by cadastre. Manual edits are overwritten on the next run. -->";

/// A generated file, addressed relative to the output directory.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Page {
    pub path: String,
    pub content: String,
}

/// Path of the index page, relative to the output directory.
pub const INDEX_PATH: &str = "index.md";

/// Renders the index page and one page per stack.
pub fn render(containers: &[Container]) -> Vec<Page> {
    let groups = group_by_stack(containers);
    let slugs = assign_slugs(groups.keys().copied());

    let mut pages = vec![Page {
        path: INDEX_PATH.to_string(),
        content: render_index(&groups, &slugs),
    }];
    pages.extend(groups.iter().map(|(stack, members)| Page {
        path: stack_path(&slugs[stack]),
        content: render_stack(stack, members),
    }));
    pages
}

fn stack_path(slug: &str) -> String {
    format!("stacks/{slug}.md")
}

fn render_index(
    groups: &BTreeMap<&str, Vec<&Container>>,
    slugs: &BTreeMap<&str, String>,
) -> String {
    let mut doc = Doc::default();
    doc.line(MARKER);
    doc.line(NOTICE);
    doc.blank();
    doc.line("# Containers overview");
    doc.blank();
    let total: usize = groups.values().map(Vec::len).sum();
    doc.line(format!(
        "{} in {}.",
        count(total, "container"),
        count(groups.len(), "stack")
    ));
    doc.blank();

    let rows: Vec<Vec<String>> = groups
        .iter()
        .map(|(stack, members)| {
            let slug = &slugs[stack];
            let label = if *stack == STANDALONE {
                "standalone"
            } else {
                slug
            };
            vec![
                format!("[{}]({})", code(label), stack_path(slug)),
                members.len().to_string(),
            ]
        })
        .collect();
    if !rows.is_empty() {
        doc.table(&["Stack", "Containers"], &rows);
    }
    doc.0
}

fn count(number: usize, noun: &str) -> String {
    if number == 1 {
        format!("1 {noun}")
    } else {
        format!("{number} {noun}s")
    }
}

/// Containers grouped by stack, each group sorted by container name.
fn group_by_stack(containers: &[Container]) -> BTreeMap<&str, Vec<&Container>> {
    let mut groups: BTreeMap<&str, Vec<&Container>> = BTreeMap::new();
    for container in containers {
        groups.entry(container.stack()).or_default().push(container);
    }
    for members in groups.values_mut() {
        members.sort_by(|a, b| a.name.cmp(&b.name));
    }
    groups
}

/// Maps every stack name to a file-name-safe, unique slug.
///
/// Compose project names are already restricted to `[a-z0-9_-]`, but the
/// output must stay safe if that ever changes, and two names must never end
/// up in the same file.
fn assign_slugs<'a>(stacks: impl Iterator<Item = &'a str>) -> BTreeMap<&'a str, String> {
    let mut taken = BTreeSet::new();
    let mut slugs = BTreeMap::new();
    for stack in stacks {
        let base = slug(stack);
        let mut candidate = base.clone();
        let mut suffix = 2;
        while !taken.insert(candidate.clone()) {
            candidate = format!("{base}-{suffix}");
            suffix += 1;
        }
        slugs.insert(stack, candidate);
    }
    slugs
}

fn slug(name: &str) -> String {
    let mapped: String = name
        .to_lowercase()
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.') {
                c
            } else {
                '-'
            }
        })
        .collect();
    // No hidden files, and never an empty name.
    match mapped.strip_prefix('.') {
        Some(rest) => format!("-{rest}"),
        None if mapped.is_empty() => "-".to_string(),
        None => mapped,
    }
}

#[derive(Default)]
struct Doc(String);

impl Doc {
    fn line(&mut self, text: impl AsRef<str>) {
        self.0.push_str(text.as_ref());
        self.0.push('\n');
    }

    fn blank(&mut self) {
        self.0.push('\n');
    }

    fn table(&mut self, headers: &[&str], rows: &[Vec<String>]) {
        self.line(format!("| {} |", headers.join(" | ")));
        self.line(format!("|{}", "---|".repeat(headers.len())));
        for row in rows {
            let cells: Vec<String> = row.iter().map(|cell| escape_cell(cell)).collect();
            self.line(format!("| {} |", cells.join(" | ")));
        }
        self.blank();
    }
}

fn render_stack(stack: &str, members: &[&Container]) -> String {
    let mut doc = Doc::default();
    doc.line(MARKER);
    doc.line(NOTICE);
    doc.blank();
    if stack == STANDALONE {
        doc.line("# Standalone containers");
    } else {
        doc.line(format!("# Stack {}", code(stack)));
    }
    doc.blank();
    doc.line(match members.len() {
        1 => "1 container.".to_string(),
        count => format!("{count} containers."),
    });
    doc.blank();

    let rows: Vec<Vec<String>> = members
        .iter()
        .map(|c| {
            vec![
                code(&c.name),
                optional_code(c.service.as_deref()),
                code(&c.image),
                optional_code(c.version.as_deref()),
                code(&c.restart_policy),
            ]
        })
        .collect();
    doc.table(
        &["Container", "Service", "Image", "Version", "Restart policy"],
        &rows,
    );

    for container in members {
        render_container(&mut doc, container);
    }
    doc.0
}

fn render_container(doc: &mut Doc, c: &Container) {
    doc.line(format!("## {}", code(&c.name)));
    doc.blank();
    doc.line(format!(
        "- **Image:** {} (id {})",
        code(&c.image),
        code(c.short_image_id())
    ));
    if let Some(version) = &c.version {
        doc.line(format!("- **Version:** {}", code(version)));
    }
    doc.line(format!("- **Restart policy:** {}", code(&c.restart_policy)));
    doc.line(format!("- **Network mode:** {}", code(&c.network_mode)));
    if !c.networks.is_empty() {
        doc.line(format!("- **Networks:** {}", code_list(&c.networks)));
    }
    if !c.env_keys.is_empty() {
        doc.line(format!(
            "- **Environment variables (names only):** {}",
            code_list(&c.env_keys)
        ));
    }
    doc.blank();

    if !c.ports.is_empty() {
        doc.line("**Ports**");
        doc.blank();
        let rows: Vec<Vec<String>> = c.ports.iter().map(port_row).collect();
        doc.table(&["Container port", "Published on"], &rows);
    }
    if !c.mounts.is_empty() {
        doc.line("**Mounts**");
        doc.blank();
        let rows: Vec<Vec<String>> = c.mounts.iter().map(mount_row).collect();
        doc.table(&["Type", "Source", "Destination", "Access"], &rows);
    }
    if !c.labels.is_empty() {
        doc.line("**Labels**");
        doc.blank();
        let rows: Vec<Vec<String>> = c
            .labels
            .iter()
            .map(|(key, value)| vec![code(key), code(value)])
            .collect();
        doc.table(&["Label", "Value"], &rows);
    }
}

fn port_row(port: &Port) -> Vec<String> {
    let published = match (&port.host_ip, port.host_port) {
        (Some(ip), Some(host_port)) => code(&host_address(ip, host_port)),
        _ => "not published".to_string(),
    };
    vec![
        code(&format!("{}/{}", port.container_port, port.protocol)),
        published,
    ]
}

fn host_address(ip: &str, port: u16) -> String {
    if ip.contains(':') {
        format!("[{ip}]:{port}")
    } else {
        format!("{ip}:{port}")
    }
}

fn mount_row(mount: &Mount) -> Vec<String> {
    vec![
        code(&mount.kind),
        optional_code(Some(&mount.source)),
        code(&mount.destination),
        if mount.read_write {
            "read-write"
        } else {
            "read-only"
        }
        .to_string(),
    ]
}

/// An inline code span that survives any content: control characters become
/// spaces and the fence is longer than any backtick run inside the text.
fn code(text: &str) -> String {
    let flat: String = text
        .chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .collect();
    if flat.trim().is_empty() {
        return "—".to_string();
    }
    let mut longest = 0;
    let mut run = 0;
    for c in flat.chars() {
        run = if c == '`' { run + 1 } else { 0 };
        longest = longest.max(run);
    }
    let fence = "`".repeat(longest + 1);
    let pad = if flat.starts_with('`') || flat.ends_with('`') {
        " "
    } else {
        ""
    };
    format!("{fence}{pad}{flat}{pad}{fence}")
}

fn optional_code(text: Option<&str>) -> String {
    text.map_or_else(|| "—".to_string(), code)
}

fn code_list(items: &[String]) -> String {
    items
        .iter()
        .map(|item| code(item))
        .collect::<Vec<_>>()
        .join(", ")
}

/// A pipe inside a table cell would end the cell, even inside a code span.
fn escape_cell(cell: &str) -> String {
    cell.replace('|', "\\|")
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use super::*;

    fn container(name: &str, project: Option<&str>) -> Container {
        Container {
            name: name.into(),
            image: "nginx:1.27".into(),
            image_id: "sha256:0123456789abcdef".into(),
            version: Some("1.27.0".into()),
            project: project.map(String::from),
            service: project.map(|_| "web".to_string()),
            restart_policy: "unless-stopped".into(),
            network_mode: "default".into(),
            ports: vec![],
            mounts: vec![],
            networks: vec!["proxy".into()],
            env_keys: vec!["APP_ENV".into()],
            labels: BTreeMap::new(),
        }
    }

    fn page<'a>(pages: &'a [Page], path: &str) -> &'a Page {
        pages
            .iter()
            .find(|p| p.path == path)
            .unwrap_or_else(|| panic!("no page {path}"))
    }

    #[test]
    fn code_spans_survive_backticks_pipes_and_line_breaks() {
        assert_eq!(code("plain"), "`plain`");
        assert_eq!(code("a`b"), "``a`b``");
        assert_eq!(code("`edge`"), "`` `edge` ``");
        assert_eq!(code("one\ntwo"), "`one two`");
        assert_eq!(code(""), "—");
        assert_eq!(code("  "), "—");
    }

    #[test]
    fn pipes_are_escaped_in_table_cells() {
        assert_eq!(escape_cell("`a|b`"), "`a\\|b`");
    }

    #[test]
    fn slugs_are_safe_file_names() {
        assert_eq!(slug("Shop_1"), "shop_1");
        assert_eq!(slug("../etc/passwd"), "-.-etc-passwd");
        assert_eq!(slug(".hidden"), "-hidden");
        assert_eq!(slug(""), "-");
        assert_eq!(slug("a b|c"), "a-b-c");
    }

    #[test]
    fn colliding_slugs_get_a_numeric_suffix() {
        let slugs = assign_slugs(["a b", "a-b", "a-b-2"].into_iter());
        assert_eq!(slugs["a b"], "a-b");
        assert_eq!(slugs["a-b"], "a-b-2");
        assert_eq!(slugs["a-b-2"], "a-b-2-2");
    }

    #[test]
    fn an_index_and_one_page_per_stack_are_rendered() {
        let containers = vec![
            container("shop-web-1", Some("shop")),
            container("shop-db-1", Some("shop")),
            container("probe", None),
        ];
        let pages = render(&containers);
        let paths: Vec<_> = pages.iter().map(|p| p.path.as_str()).collect();
        assert_eq!(
            paths,
            ["index.md", "stacks/_standalone.md", "stacks/shop.md"]
        );
    }

    #[test]
    fn the_index_links_every_stack_with_its_container_count() {
        let containers = vec![
            container("shop-web-1", Some("shop")),
            container("shop-db-1", Some("shop")),
            container("probe", None),
        ];
        let pages = render(&containers);
        let content = &page(&pages, "index.md").content;
        assert!(content.starts_with(&format!("{MARKER}\n")));
        assert!(content.contains("3 containers in 2 stacks."));
        assert!(content.contains("| [`shop`](stacks/shop.md) | 2 |"));
        assert!(content.contains("| [`standalone`](stacks/_standalone.md) | 1 |"));
    }

    #[test]
    fn an_empty_estate_still_gets_an_index() {
        let pages = render(&[]);
        assert_eq!(pages.len(), 1);
        assert!(pages[0].content.contains("0 containers in 0 stacks."));
    }

    #[test]
    fn singular_counts_are_not_pluralised() {
        let pages = render(&[container("a", Some("s"))]);
        assert!(page(&pages, "index.md")
            .content
            .contains("1 container in 1 stack."));
    }

    #[test]
    fn a_stack_page_documents_its_containers() {
        let mut web = container("shop-web-1", Some("shop"));
        web.ports = vec![
            Port {
                container_port: 80,
                protocol: "tcp".into(),
                host_ip: Some("127.0.0.1".into()),
                host_port: Some(8080),
            },
            Port {
                container_port: 9100,
                protocol: "tcp".into(),
                host_ip: None,
                host_port: None,
            },
        ];
        web.mounts = vec![Mount {
            kind: "bind".into(),
            source: "/srv/uploads".into(),
            destination: "/uploads".into(),
            read_write: false,
        }];
        web.labels.insert(
            "org.opencontainers.image.source".into(),
            "https://example.com/web".into(),
        );
        let pages = render(&[web, container("shop-db-1", Some("shop"))]);
        let content = &page(&pages, "stacks/shop.md").content;

        assert!(content.starts_with(&format!("{MARKER}\n")));
        assert!(content.contains("# Stack `shop`"));
        assert!(content.contains("2 containers."));
        assert!(content.contains("## `shop-web-1`"));
        assert!(content.contains("- **Image:** `nginx:1.27` (id `0123456789ab`)"));
        assert!(content.contains("| `80/tcp` | `127.0.0.1:8080` |"));
        assert!(content.contains("| `9100/tcp` | not published |"));
        assert!(content.contains("| `bind` | `/srv/uploads` | `/uploads` | read-only |"));
        assert!(content.contains("- **Environment variables (names only):** `APP_ENV`"));
        assert!(
            content.contains("| `org.opencontainers.image.source` | `https://example.com/web` |")
        );
        // Containers are sorted by name whatever the input order.
        assert!(content.find("## `shop-db-1`") < content.find("## `shop-web-1`"));
    }

    #[test]
    fn ipv6_addresses_are_bracketed() {
        assert_eq!(host_address("::", 80), "[::]:80");
        assert_eq!(host_address("0.0.0.0", 80), "0.0.0.0:80");
    }

    #[test]
    fn rendering_is_deterministic_and_independent_of_input_order() {
        let a = container("a", Some("s"));
        let b = container("b", Some("s"));
        let first = render(&[a.clone(), b.clone()]);
        let second = render(&[b, a]);
        assert_eq!(first, second);
    }

    #[test]
    fn hostile_names_cannot_break_out_of_the_page_structure() {
        let evil = container("x`\n# injected | <script>alert(1)</script>", Some("shop"));
        let pages = render(&[evil]);
        let content = &page(&pages, "stacks/shop.md").content;
        assert!(!content.contains("\n# injected"), "{content}");
        assert!(
            content.lines().all(|line| !line.starts_with("<script")),
            "{content}"
        );
    }
}
